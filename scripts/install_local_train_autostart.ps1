# One-time on RTX 3060 PC (Admin): schedule daily GPU train from Lightsail data + push models.
# DeployScriptVersion: 3
#
#   .\scripts\install_local_train_autostart.ps1
#   .\scripts\install_local_train_autostart.ps1 -DailyAt "03:00" -Epochs 40 -RunNow
#
# Creates: QAT-Local-TrainSync
# Expects Lightsail QAT-Data-Download (~01:00) and QAT-Paper-AutoCD already running.

param(
    [string]$RepoRoot = "",
    [string]$Branch = "main",
    [string]$DailyAt = "03:00",
    [int]$Epochs = 40,
    [string]$Tickers = "AAPL,MSFT,GOOGL,AMZN,NVDA,META,TSLA,SPY,QQQ,IWM",
    [int]$WaitForDataMinutes = 90,
    [switch]$SkipRl,
    [switch]$UseLocalDownload,
    [switch]$RunNow
)

$ErrorActionPreference = "Stop"

if (-not $RepoRoot) {
    $RepoRoot = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
}
$RepoRoot = (Resolve-Path $RepoRoot).Path

$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw "Run as Administrator on the GPU PC."
}

$fromLightsail = Join-Path $RepoRoot "scripts\train_from_lightsail_data.ps1"
$trainSync = Join-Path $RepoRoot "scripts\train_and_sync.ps1"
if ($UseLocalDownload) {
    if (-not (Test-Path $trainSync)) { throw "Missing $trainSync" }
    $entry = $trainSync
} else {
    if (-not (Test-Path $fromLightsail)) { throw "Missing $fromLightsail - git pull first" }
    $entry = $fromLightsail
}

$logs = Join-Path $RepoRoot "logs"
if (-not (Test-Path $logs)) { New-Item -ItemType Directory -Force -Path $logs | Out-Null }
$wrapper = Join-Path $RepoRoot "scripts\_run_gpu_train_logged.ps1"

if ($SkipRl) {
    Write-Host "[ok] -SkipRl ignored; the scheduled task trains PPO with the other models"
}
$skipRlFlag = ""
if ($UseLocalDownload) {
    $inner = @"
    & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path `$Root 'scripts\train_and_sync.ps1') ``
        -Branch '$Branch' -Epochs $Epochs -Tickers '$Tickers' $skipRlFlag
"@
} else {
    $inner = @"
    & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path `$Root 'scripts\train_from_lightsail_data.ps1') ``
        -Branch '$Branch' -Epochs $Epochs -Tickers '$Tickers' ``
        -WaitForDataMinutes $WaitForDataMinutes $skipRlFlag
"@
}

$wrapperBody = @"
# Auto-generated by install_local_train_autostart.ps1 — do not edit by hand
`$ErrorActionPreference = 'Continue'
`$Root = '$RepoRoot'
`$LogDir = Join-Path `$Root 'logs'
if (-not (Test-Path `$LogDir)) { New-Item -ItemType Directory -Force -Path `$LogDir | Out-Null }
`$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
`$log = Join-Path `$LogDir ("gpu-train-" + `$stamp + ".log")
Start-Transcript -Path `$log -Force | Out-Null
try {
    Set-Location `$Root
    `$env:Path = [System.Environment]::GetEnvironmentVariable('Path','Machine') + ';' +
                 [System.Environment]::GetEnvironmentVariable('Path','User')
$inner
    if (`$LASTEXITCODE -ne 0) { throw "train pipeline failed: `$LASTEXITCODE" }
} catch {
    Write-Host "[ERR] `$(`$_.Exception.Message)"
    exit 1
} finally {
    Stop-Transcript | Out-Null
}
"@
Set-Content -Path $wrapper -Value $wrapperBody -Encoding UTF8

$parts = $DailyAt.Split(":")
$hour = [int]$parts[0]
$minute = [int]$parts[1]
$trigger = New-ScheduledTaskTrigger -Daily -At (Get-Date -Hour $hour -Minute $minute -Second 0)
$action = New-ScheduledTaskAction -Execute "powershell.exe" `
    -Argument "-NoProfile -ExecutionPolicy Bypass -File `"$wrapper`"" `
    -WorkingDirectory $RepoRoot
$prin = New-ScheduledTaskPrincipal -UserId $env:USERNAME -RunLevel Highest -LogonType Interactive
# WakeToRun: unlock/sleep is OK; PC can wake for the task. Screen lock (Win+L) is fine
# while still logged in — Interactive tasks keep running. Avoid full sign-out.
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable -WakeToRun -ExecutionTimeLimit (New-TimeSpan -Hours 6)

Register-ScheduledTask -TaskName "QAT-Local-TrainSync" -Action $action -Trigger $trigger `
    -Principal $prin -Settings $settings `
    -Description "QAT: daily GPU train, then push data/models to main" -Force | Out-Null

Write-Host "[ok] Scheduled task: QAT-Local-TrainSync"
Write-Host "     Daily at $DailyAt | Branch=$Branch | Epochs=$Epochs | SkipRl=$SkipRl"
Write-Host "     Entry: $entry"
Write-Host "     WaitForDataMinutes=$WaitForDataMinutes (Lightsail path)"
Write-Host "     Logs: $logs\gpu-train-*.log"
Write-Host "     Screen LOCK is OK (stay logged in). Disable SLEEP around $DailyAt."
Write-Host "     Task has WakeToRun + StartWhenAvailable."
Write-Host "View: taskschd.msc"

if ($RunNow) {
    Write-Host "[..] RunNow GPU train pipeline..."
    & powershell -NoProfile -ExecutionPolicy Bypass -File $wrapper
    if ($LASTEXITCODE -ne 0) { throw "RunNow failed" }
    Write-Host "[ok] RunNow finished"
}
