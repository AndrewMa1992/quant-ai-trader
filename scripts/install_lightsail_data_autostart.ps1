# One-time on Lightsail (Admin): schedule daily Sydney market-data download + push.
# DeployScriptVersion: 1
#
#   .\scripts\install_lightsail_data_autostart.ps1
#   .\scripts\install_lightsail_data_autostart.ps1 -DailyAt "01:00" -ForceDownload -RunNow
#
# Creates: QAT-Data-Download (daily)
# Pair with GPU: QAT-Local-TrainSync via install_local_train_autostart.ps1
# And:          QAT-Paper-AutoCD via windows_install_autostart.ps1

param(
    [string]$RepoRoot = "C:\quant-ai-trader",
    [string]$Branch = "cursor/quant-upgrade-a75f",
    [string]$DailyAt = "01:00",
    [string]$Tickers = "AAPL,MSFT,GOOGL,AMZN,NVDA,META,TSLA,SPY,QQQ,IWM",
    [switch]$ForceDownload,
    [switch]$RunNow
)

$ErrorActionPreference = "Stop"

$env:Path = [System.Environment]::GetEnvironmentVariable("Path", "Machine") + ";" +
             [System.Environment]::GetEnvironmentVariable("Path", "User")

$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw "Run as Administrator on Lightsail."
}

if (-not (Test-Path $RepoRoot)) { throw "Missing $RepoRoot" }
$script = Join-Path $RepoRoot "scripts\lightsail_download_and_push.ps1"
if (-not (Test-Path $script)) { throw "Missing $script - git pull first" }

$logs = Join-Path $RepoRoot "logs"
if (-not (Test-Path $logs)) { New-Item -ItemType Directory -Force -Path $logs | Out-Null }
$wrapper = Join-Path $RepoRoot "scripts\_run_lightsail_data_logged.ps1"

$forceFlag = if ($ForceDownload) { "-ForceDownload" } else { "" }
$wrapperBody = @"
# Auto-generated by install_lightsail_data_autostart.ps1 — do not edit by hand
`$ErrorActionPreference = 'Continue'
`$Root = '$RepoRoot'
`$LogDir = Join-Path `$Root 'logs'
if (-not (Test-Path `$LogDir)) { New-Item -ItemType Directory -Force -Path `$LogDir | Out-Null }
`$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
`$log = Join-Path `$LogDir ("data-download-" + `$stamp + ".log")
Start-Transcript -Path `$log -Force | Out-Null
try {
    Set-Location `$Root
    `$env:Path = [System.Environment]::GetEnvironmentVariable('Path','Machine') + ';' +
                 [System.Environment]::GetEnvironmentVariable('Path','User')
    & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path `$Root 'scripts\lightsail_download_and_push.ps1') ``
        -Branch '$Branch' -Tickers '$Tickers' -RepoRoot `$Root $forceFlag
    if (`$LASTEXITCODE -ne 0) { throw "lightsail_download_and_push failed: `$LASTEXITCODE" }
} catch {
    Write-Host "[ERR] `$(`$_.Exception.Message)"
    exit 1
} finally {
    Stop-Transcript | Out-Null
}
"@
Set-Content -Path $wrapper -Value $wrapperBody -Encoding UTF8

$parts = $DailyAt.Split(":")
$hour = [int]$parts[0]
$minute = [int]$parts[1]
$trigger = New-ScheduledTaskTrigger -Daily -At (Get-Date -Hour $hour -Minute $minute -Second 0)
$action = New-ScheduledTaskAction -Execute "powershell.exe" `
    -Argument "-NoProfile -ExecutionPolicy Bypass -File `"$wrapper`"" `
    -WorkingDirectory $RepoRoot
$prin = New-ScheduledTaskPrincipal -UserId "Administrator" -RunLevel Highest -LogonType Interactive
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Hours 2)

Register-ScheduledTask -TaskName "QAT-Data-Download" -Action $action -Trigger $trigger `
    -Principal $prin -Settings $settings `
    -Description "QAT: daily Lightsail Sydney market data download + git push for GPU train" -Force | Out-Null

Write-Host "[ok] Scheduled task: QAT-Data-Download daily at $DailyAt"
Write-Host "     Branch=$Branch ForceDownload=$ForceDownload"
Write-Host "     Logs: $logs\data-download-*.log"
Write-Host "View: taskschd.msc"

if ($RunNow) {
    Write-Host "[..] RunNow data download..."
    & powershell -NoProfile -ExecutionPolicy Bypass -File $wrapper
    if ($LASTEXITCODE -ne 0) { throw "RunNow failed" }
    Write-Host "[ok] RunNow finished"
}
