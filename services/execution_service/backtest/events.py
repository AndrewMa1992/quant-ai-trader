"""services/execution_service/backtest/events.py – Event definitions.

MarketEvent → SignalEvent → OrderEvent → FillEvent → PortfolioEvent
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum


class EventType(str, Enum):
    MARKET = "MARKET"
    SIGNAL = "SIGNAL"
    ORDER = "ORDER"
    FILL = "FILL"
    PORTFOLIO = "PORTFOLIO"


@dataclass(order=True)
class Event:
    """Base event with priority queue support."""
    priority: int = field(default=0, compare=True)
    timestamp: datetime = field(default_factory=datetime.now, compare=False)
    event_type: EventType = EventType.MARKET

    def __post_init__(self):
        pass


@dataclass
class MarketEvent(Event):
    """New market data available (trigger signal generation)."""

    def __init__(self, timestamp: datetime | None = None) -> None:
        super().__init__(
            priority=0,
            timestamp=timestamp or datetime.now(),
            event_type=EventType.MARKET,
        )


@dataclass
class SignalEvent(Event):
    """Trading signal generated by strategy."""
    ticker: str = ""
    signal: float = 0.0  # [-1, 1]
    confidence: float = 0.0
    direction: str = "HOLD"

    def __init__(
        self,
        ticker: str,
        signal: float,
        confidence: float = 0.5,
        direction: str = "HOLD",
        timestamp: datetime | None = None,
    ) -> None:
        super().__init__(
            priority=1,
            timestamp=timestamp or datetime.now(),
            event_type=EventType.SIGNAL,
        )
        self.ticker = ticker
        self.signal = signal
        self.confidence = confidence
        self.direction = direction


@dataclass
class OrderEvent(Event):
    """Order to be sent to broker."""
    ticker: str = ""
    side: str = "BUY"
    quantity: int = 0
    order_type: str = "MKT"
    limit_price: float | None = None
    order_id: str = ""

    def __init__(
        self,
        ticker: str,
        side: str,
        quantity: int,
        order_type: str = "MKT",
        limit_price: float | None = None,
        timestamp: datetime | None = None,
    ) -> None:
        import uuid
        super().__init__(
            priority=2,
            timestamp=timestamp or datetime.now(),
            event_type=EventType.ORDER,
        )
        self.ticker = ticker
        self.side = side.upper()
        self.quantity = quantity
        self.order_type = order_type.upper()
        self.limit_price = limit_price
        self.order_id = str(uuid.uuid4())[:12]


@dataclass
class FillEvent(Event):
    """Order filled by broker."""
    ticker: str = ""
    side: str = ""
    quantity: int = 0
    price: float = 0.0
    commission: float = 0.0
    order_id: str = ""

    def __init__(
        self,
        ticker: str,
        side: str,
        quantity: int,
        price: float,
        commission: float = 0.0,
        order_id: str = "",
        timestamp: datetime | None = None,
    ) -> None:
        super().__init__(
            priority=3,
            timestamp=timestamp or datetime.now(),
            event_type=EventType.FILL,
        )
        self.ticker = ticker
        self.side = side.upper()
        self.quantity = quantity
        self.price = price
        self.commission = commission
        self.order_id = order_id


@dataclass
class PortfolioEvent(Event):
    """Portfolio snapshot for tracking."""
    cash: float = 0.0
    positions: dict[str, int] = field(default_factory=dict)
    total_value: float = 0.0

    def __init__(
        self,
        cash: float = 0.0,
        positions: dict[str, int] | None = None,
        total_value: float = 0.0,
        timestamp: datetime | None = None,
    ) -> None:
        super().__init__(
            priority=4,
            timestamp=timestamp or datetime.now(),
            event_type=EventType.PORTFOLIO,
        )
        self.cash = cash
        self.positions = positions or {}
        self.total_value = total_value
